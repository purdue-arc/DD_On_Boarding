import numpy as np

# Coefficient array for V(1), V(2), and V(3)
A_t = np.array([
    [1 - 0.9 * 0.95 * 0.1 - 0.1 * 0.95 * 0.8, -0.9 * 0.95 * 0.8 - 0.1 * 0.95 * 0.1, -0.9 * 0.95 * 0.1 - 0.1 * 0.95 * 0.1],
    [-0.9 * 0.95 * 0.1 - 0.1 * 0.95 * 0.1, 1 - 0.9 * 0.95 * 0.1 - 0.1 * 0.95 * 0.8, -0.9 * 0.95 * 0.8 - 0.1 * 0.95 * 0.1],
    [-0.1 * 0.95 * 0.8 - 0.9 * 0.95 * 0.1, -0.1 * 0.95 * 0.1 - 0.9 * 0.95 * 0.1, 1 - 0.1 * 0.95 * 0.1 - 0.9 * 0.95 * 0.8]
])

# Coefficient array for V(1), V(2), and V(3)
A_b = np.array([
    [1 - 0.85 * 0.95 * 0.1 - 0.15 * 0.95 * 0.8, -0.85 * 0.95 * 0.8 - 0.15 * 0.95 * 0.1, -0.85 * 0.95 * 0.1 - 0.15 * 0.95 * 0.1],
    [-0.88 * 0.95 * 0.1 - 0.12 * 0.95 * 0.1, 1 - 0.88 * 0.95 * 0.1 - 0.12 * 0.95 * 0.8, -0.88 * 0.95 * 0.8 - 0.12 * 0.95 * 0.1],
    [-0.1 * 0.95 * 0.8 - 0.9 * 0.95 * 0.1, -0.1 * 0.95 * 0.1 - 0.9 * 0.95 * 0.1, 1 - 0.1 * 0.95 * 0.1 - 0.9 * 0.95 * 0.8]
])

# Constant vector b (rewards)
b = np.array([0, 0, 0.9])

# Solve the system of equations
V_t = np.linalg.solve(A_t, b)
V_b = np.linalg.solve(A_b, b)

print("Value function V^πt:", V_t)
print("Value function V^πb:", V_b)
